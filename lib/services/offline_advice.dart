/// Rule-based offline guidance used when no AI channel is configured.
class OfflineAdvice {
  static String forStage(String stage) => switch (stage) {
        'ابتدایی' =>
          'درس را به بخش‌های کوتاه ۱۰ تا ۱۵ دقیقه‌ای تقسیم کن، بعد از هر بخش کمی استراحت داشته باش و اگر مطلبی سخت بود از معلم یا خانواده کمک بگیر.',
        'متوسطه اول' =>
          'برای هر درس هدف کوچک و مشخص تعیین کن، تکالیف را به شب آخر موکول نکن و بعد از مطالعه با چند سؤال کوتاه مطمئن شو مطلب را فهمیده‌ای.',
        'متوسطه دوم' =>
          'درس‌های مدرسه را با مرور منظم ترکیب کن، مباحث دشوار را زودتر مشخص کن و برای هر هفته زمان جبرانی در نظر بگیر.',
        'کنکوری' =>
          'برنامه را بر پایهٔ سطح فعلی و زمان باقی‌مانده بچین؛ حل تست، تحلیل اشتباه‌ها و مرور فاصله‌دار را کنار هم نگه دار و خواب را قربانی مطالعه نکن.',
        'دانشجو' =>
          'موعد تحویل پروژه‌ها و امتحان‌ها را از قبل ثبت کن، کارهای بزرگ را به گام‌های کوچک بشکن و برای مطالعهٔ مستقل و استراحت تعادل نگه دار.',
        _ =>
          'هدف شغلی یا تحصیلی بعدی را مشخص کن، مهارت‌های موردنیاز را فهرست کن و پیش از تصمیم بزرگ، اطلاعات را از چند منبع معتبر بررسی کن.',
      };

  static String forGoal(String goal) => switch (goal) {
        'برنامه‌ریزی درسی' =>
          'امروز سه کار مهم را انتخاب کن، زمان تقریبی هرکدام را مشخص کن و در پایان روز برنامه را بر اساس آنچه واقعاً انجام دادی اصلاح کن.',
        'انتخاب رشته' =>
          'علاقه‌ها، توانایی‌ها، شرایط و محدودیت‌هایت را جداگانه بنویس؛ تصمیم نهایی را فقط بر پایهٔ نظر دیگران یا یک آزمون نگذار.',
        'آزمون و کنکور' =>
          'پس از هر آزمون، اشتباه‌ها را به دانشی، بی‌دقتی و مدیریت زمان دسته‌بندی کن و برای هر دسته یک اقدام اصلاحی در نظر بگیر.',
        _ =>
          'مسیرهای تحصیلی و شغلی موردعلاقه را مقایسه کن، مهارت‌های لازم و فرصت‌های واقعی را بررسی کن و یک قدم کم‌هزینه برای تجربه‌کردن مسیر انتخاب کن.',
      };

  static String buildFallback({
    required String stage,
    required String goal,
    required String question,
  }) {
    return 'راهنمای آغازین متناسب با اطلاعات انتخاب‌شده\n\n'
        'مقطع: $stage\nموضوع: $goal\n\n'
        'پیشنهاد برای مقطع شما: ${forStage(stage)}\n\n'
        'پیشنهاد دربارهٔ موضوع انتخابی: ${forGoal(goal)}\n\n'
        'سؤال شما: «$question»\n'
        'یک اقدام کوچک و قابل سنجش برای امروز انتخاب کنید و نتیجه را بعداً ارزیابی کنید.\n\n'
        'این راهنمای قاعده‌محور و عمومی است؛ برای پاسخ اختصاصی مربی هوش مصنوعی، کلید API یا آدرس سرویس باید در ساخت برنامه تنظیم شده باشد.';
  }
}
